/**
 * Trains the photo model (is this image a photo or painting, to be kept as it is in dark mode?)
 * from tests/photo-model/dataset.json and writes src/lib/dark/photoModelWeights.ts.
 *
 *   npm run train-photo-model
 *
 * The dataset holds only numbers (the features of each image) and labels, never images.
 * Examples marked "reported" come from testers (the beta's "It's a photo / Not a photo"): the
 * model must get them right, and images that close to one take its label directly.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { FEATURE_COUNT, FEATURE_NAMES, photoProbability, type PhotoModel } from "../src/lib/dark/photoFeatures.ts";

interface Row {
  from: string;
  photo: boolean;
  f: number[];
  reported?: boolean;
}

const root = resolve(import.meta.dirname, "..");
const rows: Row[] = JSON.parse(readFileSync(`${root}/tests/photo-model/dataset.json`, "utf8"));
for (const r of rows) if (r.f.length !== FEATURE_COUNT) throw new Error(`${r.from}: ${r.f.length} features, expected ${FEATURE_COUNT}`);

// Standardise each feature.
const mean = Array.from({ length: FEATURE_COUNT }, (_, i) => rows.reduce((s, r) => s + r.f[i]!, 0) / rows.length);
const scale = mean.map((m, i) => Math.max(1e-3, Math.sqrt(rows.reduce((s, r) => s + (r.f[i]! - m) ** 2, 0) / rows.length)));
const X = rows.map((r) => r.f.map((v, i) => (v - mean[i]!) / scale[i]!));
const y = rows.map((r) => (r.photo ? 1 : 0));

// Logistic regression, L2-regularised, classes balanced; reported examples weigh more.
const positives = y.reduce((s: number, v) => s + v, 0);
const weightOf = (i: number) => (rows[i]!.reported ? 4 : 1) * (y[i] ? rows.length / (2 * positives) : rows.length / (2 * (rows.length - positives)));
const w = new Array<number>(FEATURE_COUNT).fill(0);
let b = 0;
const lambda = 0.002;
for (let epoch = 0; epoch < 6000; epoch++) {
  const gw = new Array<number>(FEATURE_COUNT).fill(0);
  let gb = 0;
  for (let i = 0; i < X.length; i++) {
    let z = b;
    for (let k = 0; k < FEATURE_COUNT; k++) z += w[k]! * X[i]![k]!;
    const err = (1 / (1 + Math.exp(-z)) - y[i]!) * weightOf(i);
    for (let k = 0; k < FEATURE_COUNT; k++) gw[k]! += err * X[i]![k]!;
    gb += err;
  }
  const lr = 0.5;
  for (let k = 0; k < FEATURE_COUNT; k++) w[k] = w[k]! - lr * (gw[k]! / X.length + lambda * w[k]!);
  b -= (lr * gb) / X.length;
}

const model: PhotoModel = {
  mean: mean.map((v) => +v.toFixed(5)),
  scale: scale.map((v) => +v.toFixed(5)),
  weights: w.map((v) => +v.toFixed(4)),
  bias: +b.toFixed(4),
  reported: [],
  reportedRadius: 0.02,
};
// Reported examples the regression still gets wrong are remembered as they are.
for (let i = 0; i < rows.length; i++) {
  if (rows[i]!.reported && photoProbability(model, rows[i]!.f) >= 0.5 !== rows[i]!.photo) {
    model.reported.push({ x: X[i]!.map((v) => +v.toFixed(4)), photo: rows[i]!.photo });
  }
}

const wrong = rows.filter((r) => photoProbability(model, r.f) >= 0.5 !== r.photo);
console.log(`${rows.length} examples (${positives} photos): ${rows.length - wrong.length} right, ${wrong.length} wrong`);
for (const r of wrong) console.log(`  wrong: ${r.from} (${r.photo ? "photo" : "not a photo"}) p=${photoProbability(model, r.f).toFixed(2)}`);
console.log(FEATURE_NAMES.map((n, i) => `${n} ${model.weights[i]}`).join(", "));

writeFileSync(
  `${root}/src/lib/dark/photoModelWeights.ts`,
  `/** Generated by scripts/train-photo-model.ts from tests/photo-model/dataset.json. Don't edit by hand. */\n` +
    `import type { PhotoModel } from "./photoFeatures";\n\n` +
    `export const PHOTO_MODEL: PhotoModel = ${JSON.stringify(model)};\n`,
);
